function isRiver(a: string, b: string): boolean {
  return RIVER_EDGES.has(`${a}|${b}`) || RIVER_EDGES.has(`${b}|${a}`);
}

export const EDGES: Edge[] = (Object.keys(LINE_SEQUENCES) as LineId[]).flatMap((line) =>
  LINE_SEQUENCES[line].flatMap((seq) => {
    const edges: Edge[] = [];
    for (let i = 0; i < seq.length - 1; i++) {
      const a = seq[i];
      const b = seq[i + 1];
      edges.push({ a, b, line, ...(isRiver(a, b) ? { river: true } : {}) });
    }
    return edges;
  }),
);

// 데이터 무결성 검사: 노선 순서 ↔ 역 정의의 lines 배열이 서로 일치하는지
for (const [lineKey, seqs] of Object.entries(LINE_SEQUENCES)) {
  const line = lineKey as LineId;
  const inSeq = new Set(seqs.flat());
  for (const name of inSeq) {
    const st = STATION_BY_ID[name];
    if (!st) throw new Error(`stations.ts: ${line} 순서에만 있고 정의되지 않은 역 — ${name}`);
    if (!st.lines.includes(line)) {
      throw new Error(`stations.ts: ${name}이 ${line} 순서에 있지만 lines에 없음`);
    }
  }
  for (const st of STATIONS) {
    if (st.lines.includes(line) && !inSeq.has(st.id)) {
      throw new Error(`stations.ts: ${st.id}의 lines에 ${line}이 있지만 노선 순서에 없음`);
    }
  }
}

