// 한강 도하 구간 (교량·하저 통과)
const RIVER_EDGES = new Set([
  '용산|노량진', // 한강철교
  '당산|합정', // 당산철교
  '강변|잠실나루', // 잠실철교
  '옥수|압구정', // 동호대교
  '이촌|동작', // 동작대교
]);

function isRiver(a: string, b: string): boolean {
  return RIVER_EDGES.has(`${a}|${b}`) || RIVER_EDGES.has(`${b}|${a}`);
}

export const EDGES: Edge[] = (Object.keys(LINE_SEQUENCES) as unknown as LineId[]).flatMap(
  (line) => {
    const seq = LINE_SEQUENCES[line];
    const edges: Edge[] = [];
    for (let i = 0; i < seq.length - 1; i++) {
      const a = seq[i];
      const b = seq[i + 1];
      edges.push({ a, b, line: Number(line) as LineId, ...(isRiver(a, b) ? { river: true } : {}) });
    }
    return edges;
  },
);

