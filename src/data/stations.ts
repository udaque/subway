// 한강 도하 구간 (교량·하저터널)
const RIVER_EDGES = new Set([
  '용산|노량진', // 한강철교 (1호선)
  '당산|합정', // 당산철교 (2호선)
  '강변|잠실나루', // 잠실철교 (2호선)
  '옥수|압구정', // 동호대교 (3호선)
  '이촌|동작', // 동작대교 (4호선)
  '여의나루|마포', // 하저터널 (5호선)
  '광나루|천호', // 하저터널 (5호선)
  '뚝섬유원지|청담', // 청담대교 (7호선)
]);

function isRiver(a: string, b: string): boolean {
  return RIVER_EDGES.has(`${a}|${b}`) || RIVER_EDGES.has(`${b}|${a}`);
}

export const EDGES: Edge[] = (Object.keys(LINE_SEQUENCES).map(Number) as LineId[]).flatMap(
  (line) =>
    LINE_SEQUENCES[line].flatMap((seq) => {
      const edges: Edge[] = [];
      for (let i = 0; i < seq.length - 1; i++) {
        const a = seq[i];
        const b = seq[i + 1];
        edges.push({ a, b, line, ...(isRiver(a, b) ? { river: true } : {}) });
      }
      return edges;
    }),
);

// 데이터 무결성 검사: 노선 순서 ↔ 역 정의의 lines 배열이 서로 일치하는지
for (const [lineKey, seqs] of Object.entries(LINE_SEQUENCES)) {
  const line = Number(lineKey) as LineId;
  const inSeq = new Set(seqs.flat());
  for (const name of inSeq) {
    const st = STATION_BY_ID[name];
    if (!st) throw new Error(`stations.ts: ${line}호선 순서에만 있고 정의되지 않은 역 — ${name}`);
    if (!st.lines.includes(line)) {
      throw new Error(`stations.ts: ${name}이 ${line}호선 순서에 있지만 lines에 ${line}이 없음`);
    }
  }
  for (const st of STATIONS) {
    if (st.lines.includes(line) && !inSeq.has(st.id)) {
      throw new Error(`stations.ts: ${st.id}의 lines에 ${line}호선이 있지만 노선 순서에 없음`);
    }
  }
}

